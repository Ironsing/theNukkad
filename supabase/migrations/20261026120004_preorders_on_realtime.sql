-- Preorders streamed to whoever is looking, so an outlet's request board and a
-- student's waiting request follow the other side's move instead of polling for it.
--
-- Added to the publication for the reason orders were: every state change here is
-- an update on a published table, and Realtime checks a policy against the record it
-- has - for an update, the row as it now is, which is what both policies are written
-- against. So an accept or a refusal reaches the student who asked and the outlet
-- that answered, and nobody else. The accept is also the student's notification that
-- the request is on, and `ready` arrives carrying the code, minted in the same
-- statement that sets ready_at.
--
-- A delete would be the problem - its record is only a primary key - and no account
-- can delete a request, so the replica identity stays at the default.
alter publication supabase_realtime add table public.preorders;

-- The lines stay out of the publication, exactly as order_items does: a change here
-- describes a request's head and never what is on it, so a page reads its list again
-- on each change rather than folding one into what it already has. Nothing extra is
-- needed for the code either, for the reason the orders file gives - it is minted in
-- the update that marks the request ready, so it arrives with it, to both sides at
-- once.
--
-- Measured against the local stack afterwards, with three subscriptions open at
-- once - the student who asked, the outlet it was addressed to, and a second outlet
-- with its own session and no request in common. A request placed by the student was
-- carried to the student and to the outlet; the accept and the cook that followed
-- were carried to the same two, the cook arriving with the code on it; and the
-- second outlet was told none of the three. So this is the policies doing their job
-- on this path too, and a page reads the table on mount as well as subscribing, since
-- Realtime carries what happens next rather than what has already happened.
--
-- A refusal is the same kind of change as an accept and needs nothing of its own: a
-- page that reads its list again on any change sees `rejected` and stops waiting.

